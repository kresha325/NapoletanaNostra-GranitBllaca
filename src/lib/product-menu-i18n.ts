const DESCRIPTIONS_BY_LANG: Record<Exclude<Language, "sq">, Record<string, string>> = {
  en: DESCRIPTIONS_EN,
  it: DESCRIPTIONS_IT,
  de: DESCRIPTIONS_DE,
  tr: DESCRIPTIONS_TR,
  fr: DESCRIPTIONS_FR,
  bs: DESCRIPTIONS_BS,
};

export function getMenuProductLabels(lang: Language): Record<string, ProductLabel> {
  if (lang === "sq") {
    return menuProductLabels;
  }

  const descriptions = DESCRIPTIONS_BY_LANG[lang] ?? DESCRIPTIONS_EN;
  const result: Record<string, ProductLabel> = {};

  for (const [key, value] of Object.entries(menuProductLabels)) {
    result[key] = {
      name: value.name,
      description: descriptions[key] ?? DESCRIPTIONS_EN[key] ?? value.description,
    };
  }

  return result;
}
